#!/usr/bin/env python3
"""NextBand assets for the native apps, from the same geometry as build.py.

Android (apps/android/app/src/main/res):
  drawable/ic_launcher_foreground.xml   adaptive icon layer (also the themed-icon monochrome layer), symbol inside the 66dp safe zone
  drawable/logo_wordmark.xml            the logo; colours from @color/logo_symbol and @color/logo_word (night variants in values-night)
  drawable/splash_icon.xml              Android 12+ splash: the pen draws the N (animated-vector, trimPathEnd under a clip of the symbol)
iOS (apps/ios/IELTS/Assets.xcassets):
  AppIcon (1024 px: light, dark, tinted), Logo (light/dark vector), LaunchMark (light/dark vector), LaunchBackground colour
Needs rsvg-convert for the iOS icon PNGs.
"""
import json, math, runpy, subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
B = runpy.run_path(str(HERE / "build.py"))
S, W, XH, CAP, BASE, ANG, T, LOCK_W, SIDE, E0 = (B[k] for k in ("S", "W", "XH", "CAP", "BASE", "ANG", "T", "LOCK_W", "SIDE", "E0"))
SYM, REST, f, mark = B["SYM"], B["REST"], B["f"], B["mark"]
TEAL, INK, MINT, NIGHT, NIGHT_INK, PAPER = (B[k] for k in ("TEAL", "INK", "MINT", "NIGHT", "NIGHT_INK", "PAPER"))
ROOT = HERE.parents[1]
RES = ROOT / "apps/android/app/src/main/res"
XC = ROOT / "apps/ios/IELTS/Assets.xcassets"
NOTE = "<!-- Generated by scripts/nextband/gen_native.py from the NextBand logo geometry. Edit the generator, not this file. -->"
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'


def centred(k, box=108):
    """Group transform placing the symbol (W wide, cap→baseline tall) at scale k in the middle of a box×box viewport."""
    return f'android:scaleX="{f(k)}" android:scaleY="{f(k)}" android:translateX="{f(box / 2 - W / 2 * k)}" android:translateY="{f(box / 2 - (CAP + BASE) / 2 * k)}"'


# ---------- Android ----------
fg_k = 108 * 0.36 / (BASE - CAP)
(RES / "drawable/ic_launcher_foreground.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
{NOTE}
<!-- The NextBand symbol, white, inside the 66dp safe zone of the 108dp adaptive-icon canvas. -->
<vector {A}
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group {centred(fg_k)}>
        <path android:fillColor="#FFFFFF" android:pathData="{SYM}" />
    </group>
</vector>
""")

H = BASE - CAP
(RES / "drawable/logo_wordmark.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
{NOTE}
<!-- NextBand logo: the symbol is the N (brand colour), then "extband" (text colour). Night colours in values-night/colors.xml. -->
<vector {A}
    android:width="{f(24 * LOCK_W / H)}dp" android:height="24dp" android:viewportWidth="{f(LOCK_W)}" android:viewportHeight="{f(H)}">
    <group android:translateY="{f(-CAP)}">
        <path android:fillColor="@color/logo_symbol" android:pathData="{SYM}" />
        <group android:translateX="{f(W + SIDE - E0)}">
            <path android:fillColor="@color/logo_word" android:pathData="{REST}" />
        </group>
    </group>
</vector>
""")

# pen centre line, as in gen_splash.py
yc = lambda x: XH - x * math.tan(ANG) + T / 2
cx = (XH + T / 2 - (CAP + S / 2)) / math.tan(ANG)
PEN = f"M{f(S / 2)} {f(BASE + 1)}L{f(S / 2)} {f(yc(S / 2))}L{f(cx)} {f(CAP + S / 2)}L{f(W - S / 2)} {f(CAP + S / 2)}L{f(W - S / 2)} {f(BASE + 1)}"
sp_k = 108 * 0.42 / H   # splash icon: 288dp canvas, the system masks to a 192dp circle; the symbol stays well inside it
(RES / "drawable/splash_icon.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
{NOTE}
<!-- Android 12+ launch splash: a pen draws the N up its 30° roof (stroke clipped to the exact symbol). Same idea as the web splash. -->
<animated-vector {A}
    xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector android:width="288dp" android:height="288dp" android:viewportWidth="108" android:viewportHeight="108">
            <group {centred(sp_k)}>
                <clip-path android:pathData="{SYM}" />
                <path android:name="pen" android:pathData="{PEN}" android:strokeColor="@color/logo_symbol"
                    android:strokeWidth="{f(S * 1.45)}" android:strokeLineCap="round" android:strokeLineJoin="round" android:trimPathEnd="0" />
            </group>
        </vector>
    </aapt:attr>
    <target android:name="pen">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="trimPathEnd" android:valueFrom="0" android:valueTo="1"
                android:startOffset="100" android:duration="850" android:interpolator="@android:interpolator/fast_out_slow_in" />
        </aapt:attr>
    </target>
</animated-vector>
""")

# ---------- iOS ----------
def write_json(p, obj):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(obj, indent=2) + "\n")


INFO = {"author": "xcode", "version": 1}
DARK = [{"appearance": "luminosity", "value": "dark"}]
write_json(XC / "Contents.json", {"info": INFO})

icon = XC / "AppIcon.appiconset"
icon.mkdir(parents=True, exist_ok=True)
svgs = {"icon-light.svg": mark("#FFFFFF", TEAL, size=1024, h=0.5),        # opaque teal tile, white symbol
        "icon-dark.svg": mark(MINT, size=1024, h=0.5),                     # iOS 18 dark: transparent, the system draws the dark backdrop
        "icon-tinted.svg": mark("#FFFFFF", size=1024, h=0.5)}              # iOS 18 tinted: grayscale, the system tints it
for name, svg in svgs.items():
    src = icon / name
    src.write_text(svg)
    subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024", str(src), "-o", str(src.with_suffix(".png"))], check=True)
    src.unlink()
write_json(icon / "Contents.json", {"images": [
    {"filename": "icon-light.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"},
    {"appearances": DARK, "filename": "icon-dark.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"},
    {"appearances": [{"appearance": "luminosity", "value": "tinted"}], "filename": "icon-tinted.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"},
], "info": INFO})


def vector_set(name, light_svg, dark_svg):
    d = XC / f"{name}.imageset"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{name.lower()}.svg").write_text(light_svg)
    (d / f"{name.lower()}-dark.svg").write_text(dark_svg)
    write_json(d / "Contents.json", {"images": [
        {"filename": f"{name.lower()}.svg", "idiom": "universal"},
        {"appearances": DARK, "filename": f"{name.lower()}-dark.svg", "idiom": "universal"},
    ], "info": INFO, "properties": {"preserves-vector-representation": True}})


vector_set("Logo", B["lockup"](TEAL, INK, pad=0), B["lockup"](MINT, NIGHT_INK, pad=0))
vector_set("LaunchMark", mark(TEAL, size=120, h=0.8), mark(MINT, size=120, h=0.8))

rgb = lambda h: {"alpha": "1.000", "red": f"0x{h[1:3]}", "green": f"0x{h[3:5]}", "blue": f"0x{h[5:7]}"}
write_json(XC / "LaunchBackground.colorset/Contents.json", {"colors": [
    {"color": {"color-space": "srgb", "components": rgb(PAPER)}, "idiom": "universal"},
    {"appearances": DARK, "color": {"color-space": "srgb", "components": rgb(NIGHT)}, "idiom": "universal"},
], "info": INFO})
print("android: ic_launcher_foreground, logo_wordmark, splash_icon · ios: AppIcon, Logo, LaunchMark, LaunchBackground")
