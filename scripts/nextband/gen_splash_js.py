#!/usr/bin/env python3
"""Writes apps/web/public/nextband/splash.js: the splash animation (same timeline as splash.html) as a self-removing
overlay for the installed app. index.html loads it only in standalone display mode, once per launch."""
import math, runpy
from pathlib import Path

B = runpy.run_path(str(Path(__file__).parent / "build.py"))
S, W, XH, CAP, BASE, ANG, T, SIDE, E0, LOCK_W = (B[k] for k in ("S", "W", "XH", "CAP", "BASE", "ANG", "T", "SIDE", "E0", "LOCK_W"))
SYM, REST, f = B["SYM"], B["REST"], B["f"]
OUT = B["OUT"] / "splash.js"

yc = lambda x: XH - x * math.tan(ANG) + T / 2
cx = (XH + T / 2 - (CAP + S / 2)) / math.tan(ANG)
PEN = f"M{f(S / 2)} {f(BASE + 1)}L{f(S / 2)} {f(yc(S / 2))}L{f(cx)} {f(CAP + S / 2)}L{f(W - S / 2)} {f(CAP + S / 2)}L{f(W - S / 2)} {f(BASE + 1)}"
APEX_LEN = (BASE + 1 - yc(S / 2)) + math.dist((S / 2, yc(S / 2)), (cx, CAP + S / 2)) + (W - S / 2 - cx)
PAD = 16
VB = f"{-PAD} {f(CAP - PAD)} {f(LOCK_W + 2 * PAD)} {f(BASE - CAP + 2 * PAD)}"

js = f"""// NextBand launch splash for the installed app (generated by the logo build; edit the generator, not this file).
// The pen draws the N climbing its 30° roof, the symbol lifts once, the wordmark wipes in, then the layer fades away.
// Tap to skip. Not shown with prefers-reduced-motion.
// Slow website load (index.html sets window.__nbSplashWait): it stays until main.tsx calls window.__nbSplashClose(), leaving at the earliest
// once the N is drawn and holding on the full lockup if the app is still loading; it never starts if the app got ready first (window.__nbReady).
(() => {{
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const waiting = !!window.__nbSplashWait;
  if (waiting && window.__nbReady) return;
  let ready = !waiting;
  window.__nbSplashClose = () => {{ ready = true; }};
  const dark = document.documentElement.classList.contains('dark');
  const c = dark ? {{ bg: '#0A111C', sym: '#2DD4BF', word: '#E6EDF5', tag: '#8C9AAE' }} : {{ bg: '#F7F9FB', sym: '#0F766E', word: '#0F172A', tag: '#5B6B80' }};
  const el = document.createElement('div');
  el.setAttribute('aria-hidden', 'true');
  el.style.cssText = `position:fixed;inset:0;z-index:2147483647;display:grid;place-items:center;background:${{c.bg}};transition:opacity .35s ease-out;cursor:pointer`;
  el.innerHTML = `<div style="display:flex;flex-direction:column;align-items:center;gap:clamp(10px,2.4vh,22px);width:min(86vw,560px)">
<svg viewBox="{VB}" style="width:100%;height:auto;display:block;overflow:visible">
<defs><mask id="nb-pen" maskUnits="userSpaceOnUse" x="-40" y="-40" width="600" height="200"><path d="{PEN}" fill="none" stroke="#fff" stroke-width="{f(S * 1.45)}" stroke-linejoin="round" stroke-linecap="round"/></mask>
<clipPath id="nb-wipe"><rect x="{f(W)}" y="{f(CAP - 10)}" width="0" height="{f(BASE - CAP + 20)}"/></clipPath></defs>
<g><path d="{SYM}" fill="${{c.sym}}" mask="url(#nb-pen)"/><g clip-path="url(#nb-wipe)"><path fill="${{c.word}}" opacity="0" transform="translate({f(W + SIDE - E0)} 0)" d="{REST}"/></g></g>
</svg><p style="margin:0;font:500 clamp(15px,2.2vw,19px)/1.4 'Hanken Grotesk Variable','Hanken Grotesk',system-ui,sans-serif;color:${{c.tag}};opacity:0">One band ahead.</p></div>`;
  (document.body ?? document.documentElement).appendChild(el);
  const svg = el.querySelector('svg'), pen = svg.querySelector('mask path'), lock = svg.querySelector('g');
  const sym = lock.firstElementChild, word = lock.lastElementChild.firstElementChild, wipe = svg.querySelector('clipPath rect'), tag = el.querySelector('p');
  const len = pen.getTotalLength(), apex = {f(APEX_LEN)} / len;
  const WORD_W = {f(LOCK_W - W)}, BIG = 2.4, SYM_CX = {f(W / 2)}, LOCK_CX = {f(LOCK_W / 2)}, MID = {f((CAP + BASE) / 2)}, END = 2750;
  const clamp = (v) => Math.min(1, Math.max(0, v));
  const span = (t, a, b) => clamp((t - a) / (b - a));
  const io = (p) => (p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2);
  const out = (p) => 1 - Math.pow(1 - p, 3);
  const outBack = (p) => 1 + 2.2 * Math.pow(p - 1, 3) + 1.2 * Math.pow(p - 1, 2);
  pen.style.strokeDasharray = len;
  const frame = (t) => {{
    const climb = io(span(t, 250, 1050)), drop = out(span(t, 1050, 1270));
    pen.style.strokeDashoffset = len * (1 - (climb < 1 ? climb * apex : apex + drop * (1 - apex)));
    const lift = span(t, 1180, 1520), bump = Math.sin(Math.PI * lift) * (1 - lift * 0.4);
    const move = io(span(t, 1350, 1900)), k = BIG + (1 - BIG) * move, x = SYM_CX + (LOCK_CX - SYM_CX) * move;
    lock.setAttribute('transform', `translate(${{LOCK_CX}} ${{MID - bump * 3}}) scale(${{k}}) translate(${{-x}} ${{-MID}})`);
    wipe.setAttribute('width', WORD_W * out(span(t, 1600, 2250)) + 10);
    word.setAttribute('opacity', span(t, 1600, 1750));
    const tg = span(t, 2150, 2650);
    tag.style.opacity = out(tg);
    tag.style.transform = `translateY(${{(1 - outBack(tg)) * 8}}px)`;
  }};
  let start, done = false;
  const close = () => {{
    if (done) return;
    done = true;
    sym.removeAttribute('mask');
    el.style.opacity = '0';
    setTimeout(() => el.remove(), 400);
  }};
  el.addEventListener('click', close);
  const MIN = 1300; // the N drawn and lifted: the earliest a waiting splash leaves
  const loop = (now) => {{
    if (done) return;
    start ??= now;
    const t = now - start;
    if (t <= END) frame(t);
    if (waiting ? ready && t >= MIN : t >= END + 250) close();
    else requestAnimationFrame(loop);
  }};
  requestAnimationFrame(loop);
}})();
"""
OUT.write_text(js)
print(OUT, len(js), "bytes")
